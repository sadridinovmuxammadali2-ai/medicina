const LanguageContext = createContext<LanguageContextType>({
  currentLanguage: 'UZB',
  setLanguage: () => {},
  t: (key) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLanguage, setCurrentLanguageState] = useState<LanguageCode>(() => {
    const saved = localStorage.getItem('smartlab_language');
    return (saved as LanguageCode) || 'UZB';
  });

  const setLanguage = (lang: LanguageCode) => {
    setCurrentLanguageState(lang);
    localStorage.setItem('smartlab_language', lang);
  };

  const t = (key: string): string => {
    const langDict = translations[currentLanguage] || translations.UZB;
    return langDict[key] || translations.UZB[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ currentLanguage, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
